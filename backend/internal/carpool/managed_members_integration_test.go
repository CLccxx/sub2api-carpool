func managedTestNode(t *testing.T) (*sql.DB, *NodeControl, Config) {
	t.Helper()
	db := mainTestDB(t)
	_, err := db.Exec(`ALTER TABLE users ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (START WITH 101);
 ALTER TABLE users ADD COLUMN email TEXT NOT NULL DEFAULT '', ADD COLUMN password_hash TEXT NOT NULL DEFAULT '',
 ADD COLUMN role TEXT NOT NULL DEFAULT 'user', ADD COLUMN concurrency INTEGER NOT NULL DEFAULT 5,
 ADD COLUMN restrict_public_groups BOOLEAN NOT NULL DEFAULT FALSE, ADD COLUMN balance_notify_enabled BOOLEAN NOT NULL DEFAULT TRUE;
 CREATE TABLE groups(id BIGINT PRIMARY KEY,status TEXT NOT NULL DEFAULT 'active',deleted_at TIMESTAMPTZ);
 INSERT INTO groups(id) VALUES(7),(8);
 CREATE TABLE user_allowed_groups(user_id BIGINT REFERENCES users(id),group_id BIGINT REFERENCES groups(id),PRIMARY KEY(user_id,group_id));
 CREATE TABLE user_subscriptions(id BIGSERIAL PRIMARY KEY,user_id BIGINT REFERENCES users(id));
 CREATE TABLE auth_identities(user_id BIGINT REFERENCES users(id),provider_type TEXT,provider_key TEXT,provider_subject TEXT);`)
	require.NoError(t, err)
	cfg := Config{Enabled: true, AuthorizationMode: "managed", MainInstanceID: uuid.NewString(), NodeID: uuid.NewString(), CarID: uuid.NewString(), GroupID: 7}
	node, err := NewNodeControl(context.Background(), db, cfg)
	require.NoError(t, err)
	return db, node, cfg
}

func TestManagedMembersAtomicProvisionAndStableSubjects(t *testing.T) {
	db, node, cfg := managedTestNode(t)
	ctx := context.Background()
	subject := uuid.NewString()
	var wg sync.WaitGroup
	type outcome struct {
		member ManagedMember
		err    error
	}
	results := make(chan outcome, 12)
	for range 12 {
		wg.Add(1)
		go func() {
			defer wg.Done()
			member, err := node.Provision(ctx, node.Target(), subject)
			results <- outcome{member, err}
		}()
	}
	wg.Wait()
	close(results)
	var member ManagedMember
	for result := range results {
		require.NoError(t, result.err)
		if member.UserID == 0 {
			member = result.member
		} else {
			require.Equal(t, member.UserID, result.member.UserID)
		}
	}
	require.Equal(t, subject, member.Subject)
	require.Equal(t, "prepared", member.Status)
	require.Zero(t, member.Version)
	var balance float64
	var role, password, email string
	var restricted, notify bool
	require.NoError(t, db.QueryRow(`SELECT balance,role,password_hash,email,restrict_public_groups,balance_notify_enabled FROM users WHERE id=$1`, member.UserID).Scan(&balance, &role, &password, &email, &restricted, &notify))
	require.Zero(t, balance)
	require.Equal(t, "user", role)
	require.True(t, restricted)
	require.False(t, notify)
	require.Contains(t, email, ".invalid")
	require.Contains(t, password, "!managed:")
	var count int
	require.NoError(t, db.QueryRow(`SELECT count(*) FROM users`).Scan(&count))
	require.Equal(t, 101, count)
	require.NoError(t, db.QueryRow(`SELECT count(*) FROM user_subscriptions`).Scan(&count))
	require.Zero(t, count)
	require.NoError(t, db.QueryRow(`SELECT count(*) FROM auth_identities`).Scan(&count))
	require.Zero(t, count)
	var group int64
	require.NoError(t, db.QueryRow(`SELECT group_id FROM user_allowed_groups WHERE user_id=$1`, member.UserID).Scan(&group))
	require.EqualValues(t, 7, group)
	require.ErrorIs(t, NewGate(db, cfg).CheckUser(ctx, member.UserID), ErrRequired)
	wrongTarget := node.Target()
	wrongTarget.NodeID = uuid.NewString()
	_, err := node.Provision(ctx, wrongTarget, subject)
	require.ErrorIs(t, err, ErrControlTarget)
	_, err = node.Provision(ctx, node.Target(), "not-a-stable-uuid")
	require.ErrorIs(t, err, ErrMainInvalid)
	changedConfig := cfg
	changedConfig.GroupID = 8
	_, err = NewNodeControl(ctx, db, changedConfig)
	require.ErrorIs(t, err, ErrMainConflict)
	_, err = db.Exec(`CREATE FUNCTION reject_managed_mapping() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN RAISE EXCEPTION 'synthetic mapping failure'; END $$;
 CREATE TRIGGER reject_managed_mapping BEFORE INSERT ON carpool_managed_members FOR EACH ROW EXECUTE FUNCTION reject_managed_mapping()`)
	require.NoError(t, err)
	_, err = node.Provision(ctx, node.Target(), uuid.NewString())
	require.Error(t, err)
	require.NoError(t, db.QueryRow(`SELECT count(*) FROM users`).Scan(&count))
	require.Equal(t, 101, count, "mapping failure must roll back internal user creation")
	_, err = db.Exec(`DROP TRIGGER reject_managed_mapping ON carpool_managed_members`)
	require.NoError(t, err)
	again, err := NewNodeControl(ctx, db, cfg)
	require.NoError(t, err)
	replayed, err := again.Provision(ctx, again.Target(), subject)
	require.NoError(t, err)
	require.Equal(t, member.UserID, replayed.UserID)
	_, err = db.Exec(`UPDATE users SET deleted_at=clock_timestamp() WHERE id=$1`, member.UserID)
	require.NoError(t, err)
	_, err = again.Provision(ctx, again.Target(), subject)
	require.ErrorIs(t, err, ErrRequired, "deleted managed identities must never be reassigned")
}

func TestManagedGrantVersionsLeaseAndGate(t *testing.T) {
	db, node, cfg := managedTestNode(t)
	ctx := context.Background()
	subject := uuid.NewString()
	member, err := node.Provision(ctx, node.Target(), subject)
	require.NoError(t, err)
	gate := NewGate(db, cfg)
	require.ErrorIs(t, gate.CheckUser(ctx, member.UserID), ErrRequired)
	now := time.Now().UTC().Truncate(time.Microsecond)
	start, end, lease := now.Add(-time.Hour), now.Add(time.Hour), now.Add(time.Minute)
	grant := ManagedGrant{Version: 1, Status: "active", ValidFrom: &start, ValidUntil: &end, LeaseUntil: &lease}
	require.NoError(t, node.ApplyGrant(ctx, node.Target(), subject, grant))
	require.NoError(t, node.ApplyGrant(ctx, node.Target(), subject, grant))
	require.NoError(t, gate.CheckUser(ctx, member.UserID))
	require.NoError(t, gate.CheckUser(ctx, member.UserID), "gate checks a previously successful user again")
	conflict := grant
	conflict.Status = "paused"
	require.ErrorIs(t, node.ApplyGrant(ctx, node.Target(), subject, conflict), ErrVersionConflict)
	require.NoError(t, node.ApplyGrant(ctx, node.Target(), subject, ManagedGrant{Version: 2, Status: "paused"}))
	require.ErrorIs(t, gate.CheckUser(ctx, member.UserID), ErrRequired)
	require.ErrorIs(t, node.ApplyGrant(ctx, node.Target(), subject, grant), ErrVersionConflict)
	grant.Version = 3
	tooLong := now.Add(16 * time.Minute)
	grant.LeaseUntil = &tooLong
	require.ErrorIs(t, node.ApplyGrant(ctx, node.Target(), subject, grant), ErrControlGrantWindow)
	grant.LeaseUntil = &lease
	require.NoError(t, node.ApplyGrant(ctx, node.Target(), subject, grant))
	require.NoError(t, gate.CheckUser(ctx, member.UserID))
	_, err = db.Exec(`UPDATE carpool_managed_members SET lease_until=clock_timestamp()-interval '1 second' WHERE subject_id=$1`, subject)
	require.NoError(t, err)
	require.ErrorIs(t, gate.CheckUser(ctx, member.UserID), ErrRequired)
	grant.Version = 4
	require.NoError(t, node.ApplyGrant(ctx, node.Target(), subject, grant))
	_, err = db.Exec(`UPDATE users SET status='disabled' WHERE id=$1`, member.UserID)
	require.NoError(t, err)
	require.ErrorIs(t, gate.CheckUser(ctx, member.UserID), ErrRequired)
	_, err = db.Exec(`UPDATE users SET status='active' WHERE id=$1`, member.UserID)
	require.NoError(t, err)
	require.NoError(t, node.ApplyGrant(ctx, node.Target(), subject, ManagedGrant{Version: 5, Status: "revoked"}))
	require.ErrorIs(t, gate.CheckUser(ctx, member.UserID), ErrRequired)
	require.ErrorIs(t, gate.CheckIdentity(ctx, cfg.MainInstanceID, subject), ErrRequired, "managed identities are not OIDC identities")
	require.ErrorIs(t, gate.CheckUser(ctx, 1), ErrRequired, "local administrator keys have no model gate bypass")
}

func TestManagedGrantDatabaseRejectsPartialState(t *testing.T) {
	db, node, _ := managedTestNode(t)
	subject := uuid.NewString()
	_, err := node.Provision(context.Background(), node.Target(), subject)
	require.NoError(t, err)
	_, err = db.Exec(`UPDATE carpool_managed_members SET version=1,status='active',payload_hash=repeat('a',64),
 valid_from=clock_timestamp()-interval '1 hour',valid_until=NULL,lease_until=clock_timestamp()+interval '1 minute' WHERE subject_id=$1`, subject)
	require.Error(t, err, "an active grant with a null service end must violate the database constraint")
	_, err = db.Exec(`UPDATE carpool_managed_members SET version=1,status='prepared',payload_hash='' WHERE subject_id=$1`, subject)
	require.Error(t, err, "a versioned grant must have a replay digest")
}
