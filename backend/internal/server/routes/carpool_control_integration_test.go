type controlHTTPSettings struct {
	service.SettingRepository
	key string
}

func (s *controlHTTPSettings) GetValue(_ context.Context, key string) (string, error) {
	if key == service.SettingKeyAdminAPIKey {
		return s.key, nil
	}
	return "", service.ErrSettingNotFound
}

type controlHTTPUsers struct{ carpoolHTTPUserRepository }

func (r *controlHTTPUsers) GetFirstAdmin(ctx context.Context) (*service.User, error) {
	return r.GetByID(ctx, 1)
}

func TestCarpoolControlHTTPPostgresAdminKey(t *testing.T) {
	ctx := context.Background()
	container, err := tcpostgres.Run(ctx, "postgres:18.1-alpine3.23", tcpostgres.WithDatabase("control_http"), tcpostgres.WithUsername("carpool"), tcpostgres.WithPassword("synthetic-only"), tcpostgres.BasicWaitStrategies())
	require.NoError(t, err)
	t.Cleanup(func() { require.NoError(t, container.Terminate(ctx)) })
	dsn, err := container.ConnectionString(ctx, "sslmode=disable")
	require.NoError(t, err)
	db, err := sql.Open("postgres", dsn)
	require.NoError(t, err)
	t.Cleanup(func() { require.NoError(t, db.Close()) })
	_, err = db.Exec(`CREATE TABLE users(id BIGINT PRIMARY KEY,status TEXT NOT NULL,deleted_at TIMESTAMPTZ,balance NUMERIC NOT NULL DEFAULT 0); INSERT INTO users(id,status) VALUES(1,'active'),(2,'active')`)
	require.NoError(t, err)
	require.NoError(t, carpool.Migrate(ctx, db))
	users := &controlHTTPUsers{carpoolHTTPUserRepository{users: map[int64]service.User{
		1: {ID: 1, Role: service.RoleAdmin, Email: "admin@example.test", Status: service.StatusActive},
		2: {ID: 2, Role: service.RoleUser, Email: "member@example.test", Status: service.StatusActive},
	}}}
	cfg := &config.Config{}
	cfg.JWT.Secret = "synthetic-control-http-jwt-secret"
	cfg.JWT.AccessTokenExpireMinutes = 15
	auth := service.NewAuthService(nil, users, nil, nil, cfg, nil, nil, nil, nil, nil, nil, nil, nil)
	userService := service.NewUserService(users, nil, nil, nil)
	settings := service.NewSettingService(&controlHTTPSettings{key: "synthetic-B-admin-key"}, cfg)
	nodeCfg := carpool.Config{Enabled: true, AuthorizationMode: "managed", MainInstanceID: uuid.NewString(), NodeID: uuid.NewString(), CarID: uuid.NewString(), GroupID: 1}
	node, err := carpool.NewNodeControl(ctx, db, nodeCfg)
	require.NoError(t, err)
	next := middleware.StepUpAuthMiddleware(func(c *gin.Context) { c.Next() })
	r := gin.New()
	// Positive local harness omits compliance only; production 423 is verified separately.
	registerCarpoolControlAdminRoutes(r.Group("/api/v1/admin", gin.HandlerFunc(middleware.NewAdminAuthMiddleware(auth, userService, settings, nil))), &handler.Handlers{CarpoolControl: handler.NewCarpoolControlHandler(nil, node, nil)}, next)
	for _, key := range []string{"", "synthetic-A-admin-key", "synthetic-B-admin-key"} {
		req := httptest.NewRequest("GET", "/api/v1/admin/carpool-control/v1/info", nil)
		req.Header.Set("x-api-key", key)
		w := httptest.NewRecorder()
		r.ServeHTTP(w, req)
		if key != "synthetic-B-admin-key" {
			require.Equal(t, 401, w.Code)
			continue
		}
		require.Equal(t, 200, w.Code, w.Body.String())
		require.Equal(t, "no-store", w.Header().Get("Cache-Control"))
		require.NotContains(t, w.Body.String(), key)
		var result struct {
			Data carpool.ControlInfo `json:"data"`
		}
		require.NoError(t, json.Unmarshal(w.Body.Bytes(), &result))
		require.Equal(t, node.Info(), result.Data)
	}
	member, err := users.GetByID(ctx, 2)
	require.NoError(t, err)
	token, err := auth.GenerateToken(ctx, member)
	require.NoError(t, err)
	req := httptest.NewRequest("GET", "/api/v1/admin/carpool-control/v1/info", nil)
	req.Header.Set("Authorization", "Bearer "+token)
	w := httptest.NewRecorder()
	r.ServeHTTP(w, req)
	require.Equal(t, 403, w.Code, w.Body.String())
	_, err = db.Exec(`ALTER TABLE users ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (START WITH 101);
 ALTER TABLE users ADD COLUMN email TEXT NOT NULL DEFAULT '',ADD COLUMN password_hash TEXT NOT NULL DEFAULT '',ADD COLUMN role TEXT NOT NULL DEFAULT 'user',
 ADD COLUMN concurrency INTEGER NOT NULL DEFAULT 5,ADD COLUMN restrict_public_groups BOOLEAN NOT NULL DEFAULT FALSE,ADD COLUMN balance_notify_enabled BOOLEAN NOT NULL DEFAULT TRUE;
 CREATE TABLE groups(id BIGINT PRIMARY KEY,status TEXT NOT NULL,deleted_at TIMESTAMPTZ); INSERT INTO groups(id,status) VALUES(1,'active');
 CREATE TABLE user_allowed_groups(user_id BIGINT,group_id BIGINT,PRIMARY KEY(user_id,group_id))`)
	require.NoError(t, err)
	subject := uuid.NewString()
	memberPath := "/api/v1/admin/carpool-control/v1/members/" + subject
	command := func(path, body string, target carpool.ManagedTarget, want int) *httptest.ResponseRecorder {
		t.Helper()
		req := httptest.NewRequest("PUT", path, strings.NewReader(body))
		req.Header.Set("x-api-key", "synthetic-B-admin-key")
		req.Header.Set("X-Carpool-Main-ID", target.MainID)
		req.Header.Set("X-Carpool-Node-ID", target.NodeID)
		req.Header.Set("X-Carpool-Car-ID", target.CarID)
		req.Header.Set("X-Carpool-Instance-ID", target.InstanceID)
		w := httptest.NewRecorder()
		r.ServeHTTP(w, req)
		require.Equal(t, want, w.Code, w.Body.String())
		return w
	}
	command(memberPath, `{}`, carpool.ManagedTarget{}, 400)
	command(memberPath, `{"role":"admin","balance":999,"user_id":1}`, node.Target(), 400)
	command(memberPath, `{}`, node.Target(), 200)
	command(memberPath, `{}`, node.Target(), 200)
	var prepared int
	require.NoError(t, db.QueryRow(`SELECT count(*) FROM carpool_managed_members WHERE subject_id=$1 AND status='prepared' AND version=0`, subject).Scan(&prepared))
	require.Equal(t, 1, prepared)
	command(memberPath+"/grant", `{"version":1,"status":"prepared"}`, node.Target(), 200)
	command(memberPath+"/grant", `{"version":1,"status":"prepared"}`, node.Target(), 200)
	command(memberPath+"/grant", `{"version":1,"status":"revoked"}`, node.Target(), 409)
	wrong := node.Target()
	wrong.InstanceID = uuid.NewString()
	command(memberPath+"/grant", `{"version":2,"status":"revoked"}`, wrong, 400)
	// Create a separate schema/database role for A; the node identity is never reused.
	_, err = db.Exec(`CREATE SCHEMA main_control; SET search_path TO main_control`)
	require.NoError(t, err)
	db.SetMaxOpenConns(1)
	_, err = db.Exec(`CREATE TABLE users(id BIGINT PRIMARY KEY,status TEXT NOT NULL,deleted_at TIMESTAMPTZ,balance NUMERIC NOT NULL DEFAULT 0); INSERT INTO users(id,status) VALUES(1,'active'),(2,'active')`)
	require.NoError(t, err)
	require.NoError(t, carpool.Migrate(ctx, db))
	main := carpool.NewMainService(db, carpool.MainConfig{Enabled: true, TestOrdersEnabled: true})
	car, err := main.CreateCar(ctx, 1, carpool.CarInput{Name: "control test", Capacity: 2, PriceMinor: 100, Currency: "CNY", ServiceDays: 30, RecruitUntil: time.Now().Add(time.Hour), DeliveryHours: 24, RefundPolicy: "synthetic"})
	require.NoError(t, err)
	_, err = main.PublishCar(ctx, 1, car.ID)
	require.NoError(t, err)
	registered, err := main.RegisterNode(ctx, 1, carpool.NodeInput{CarID: car.ID, Hostname: "node.example"})
	require.NoError(t, err)
	store, err := carpool.NewControlStore(ctx, main, base64.StdEncoding.EncodeToString(bytes.Repeat([]byte{5}, 32)), []string{"https://node.example"})
	require.NoError(t, err)
	r = gin.New()
	mainSettings := service.NewSettingService(&controlHTTPSettings{key: "synthetic-A-admin-key"}, cfg)
	registerCarpoolControlAdminRoutes(r.Group("/api/v1/admin", gin.HandlerFunc(middleware.NewAdminAuthMiddleware(auth, userService, mainSettings, nil))), &handler.Handlers{CarpoolControl: handler.NewCarpoolControlHandler(store, nil, nil)}, next)
	body := `{"origin":"https://node.example","node_instance_id":"` + node.Info().InstanceID + `","admin_key":"synthetic-node-key","expected_generation":0}`
	for _, want := range []int{200, 409} {
		req := httptest.NewRequest("PUT", "/api/v1/admin/carpool/nodes/"+registered.ID+"/connection", strings.NewReader(body))
		req.Header.Set("x-api-key", "synthetic-A-admin-key")
		w := httptest.NewRecorder()
		r.ServeHTTP(w, req)
		require.Equal(t, want, w.Code, w.Body.String())
		require.NotContains(t, w.Body.String(), "synthetic-node-key")
	}
}
